#!/usr/bin/env bash
# Regenerates docs/CODEMAP.md: symbol index (file:line) so agents need not grep.
cd "$(dirname "$0")/.." || exit 1
out=docs/CODEMAP.md
{
echo "# CODEMAP (generated by tools/gen_codemap.sh — do not edit)"
echo
echo "Symbol -> line. Read files with offset/limit (or sed -n A,Bp) at these lines instead of grepping."
for f in rust/src/*.rs; do
  echo; echo "## $f"
  grep -nE '^\s*(pub(\([a-z]+\))? )?(const fn|fn|struct|enum|trait|impl|mod|const|static|type) ' "$f" \
    | grep -v 'fn test_'  | sed -E 's/\s*\{\s*$//; s/^([0-9]+):\s*/\1 /' | cut -c1-110
done
for f in scripts/*.gd scripts/ui/*.gd; do
  echo; echo "## $f"
  grep -nE '^(class_name|extends|func|signal|const|enum|class) ' "$f" | sed -E 's/^([0-9]+):/\1 /' | cut -c1-110
done
echo; echo "## README.md headings (line text)"
awk '/^#+ /{print NR, $0}' README.md
} > "$out"
